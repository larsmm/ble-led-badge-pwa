import { describe, expect, it } from "vitest";

import { bytesToHex } from "../lib/badge-protocol";
import {
  binaryStringsToGrid,
  encodeBadgeImagePixels,
  gridToBinaryStrings
} from "../features/images";

describe("custom image encoding", () => {
  it("matches the Python sunglasses bitmap example", () => {
    const grid = binaryStringsToGrid([
      "000000000000000000000000000000000000000000000000",
      "000000000000000000000000000000000000000000000000",
      "000111111111000000000000000000001111111110000000",
      "001111111111100000000000000000011111111111000000",
      "011111111111110000111111110000111111111111100000",
      "011111111111110000111111110000111111111111100000",
      "011111111111110000111111110000111111111111100000",
      "011111111111110000111111110000111111111111100000",
      "001111111111100000011111100000011111111111000000",
      "000111111111000000000000000000001111111110000000",
      "000000000000000000000000000000000000000000000000",
      "000000000000000000000000000000000000000000000000"
    ]);

    expect(bytesToHex(encodeBadgeImagePixels(grid))).toBe(
      "00000f1f8c3f3fcc3f3fcc3f3fcc3f3fcc3f1f800f0000000000000f080f0f880f0f880f0f800f0000000000000f081f3fcc3f3fcc3f3fcc3f3fcc3f3fc81f0f0000000000000000"
    );
  });

  it("round-trips preset rows without losing pixel data", () => {
    const rows = [
      "100000000000000000000000000000000000000000000001",
      "010000000000000000000000000000000000000000000010",
      "001000000000000000000000000000000000000000000100",
      "000100000000000000000000000000000000000000001000",
      "000010000000000000000000000000000000000000010000",
      "000001000000000000000000000000000000000000100000",
      "000000100000000000000000000000000000000001000000",
      "000000010000000000000000000000000000000010000000",
      "000000001000000000000000000000000000000100000000",
      "000000000100000000000000000000000000001000000000",
      "000000000010000000000000000000000000010000000000",
      "000000000001000000000000000000000000100000000000"
    ];

    expect(gridToBinaryStrings(binaryStringsToGrid(rows))).toEqual(rows);
  });
});
